export function buildResumeDefenseScanMessages(targetRole: string, resumeContent: string): SafeMessage[] {
  const parts: PromptPart[] = [];
  if (targetRole) {
    parts.push(
      { trust: "trusted", text: "【目标岗位】\n" },
      { trust: "untrusted", tag: "target_role", text: targetRole },
      { trust: "trusted", text: "\n\n" },
    );
  }
  parts.push(
    { trust: "trusted", text: "【候选人简历】\n" },
    { trust: "untrusted", tag: "candidate_resume", text: resumeContent },
    { trust: "trusted", text: "\n\n请扫描有原文依据的风险，给出具体点评、追问与诚实可用的防御预案；没有明确问题时不要凑数。" },
  );
  return [{
    role: "user",
    parts,
  }];
}
